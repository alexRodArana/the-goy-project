import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('workout creation, numeric entry, completion, history and previous-set fallback', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Crear rutina', exact: true }).click()
  await page.getByLabel('Nombre', { exact: true }).fill('Push')
  await page.getByLabel('Ejercicio', { exact: true }).fill('Press banca')
  await page.getByLabel('Series', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('combobox')).toHaveValue(/routine-/)
  await page.getByRole('button', { name: 'Iniciar', exact: true }).click()
  await expect(page.getByLabel('Peso', { exact: true }).first()).toHaveAttribute('inputmode', 'decimal')
  await expect(page.getByLabel('Reps', { exact: true }).first()).toHaveAttribute('inputmode', 'numeric')
  await page.getByLabel('Peso', { exact: true }).first().fill('80')
  await page.getByLabel('Reps', { exact: true }).first().fill('10')
  await page.getByRole('button', { name: 'Completar serie', exact: true }).first().click()
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '50')
  await page.screenshot({ path: info.outputPath('workout.png'), fullPage: true, animations: 'disabled' })
  const workoutAccessibility = await new AxeBuilder({ page }).disableRules(['meta-viewport']).analyze()
  expect(workoutAccessibility.violations.filter((issue) => ['serious', 'critical'].includes(issue.impact ?? ''))).toEqual([])
  await page.getByRole('button', { name: 'Terminar', exact: true }).click()
  await page.getByRole('button', { name: 'Push', exact: true }).click()
  await expect(page.getByText(/Inicio .* Fin/)).toBeVisible()
  await expect(page.getByLabel('Editar entrenamiento')).toBeVisible()
  await page.screenshot({ path: info.outputPath('history.png'), fullPage: true, animations: 'disabled' })
  const historyAccessibility = await new AxeBuilder({ page }).disableRules(['meta-viewport']).analyze()
  expect(historyAccessibility.violations.filter((issue) => ['serious', 'critical'].includes(issue.impact ?? ''))).toEqual([])
  await page.getByRole('button', { name: 'Training', exact: true }).click()
  await page.getByRole('button', { name: 'Iniciar', exact: true }).click()
  await expect(page.getByLabel('Peso', { exact: true }).first()).toHaveAttribute('placeholder', '80')
  await page.getByRole('button', { name: 'Completar serie', exact: true }).first().click()
  await expect(page.getByLabel('Peso', { exact: true }).first()).toHaveValue('80')
  await expect(page.getByLabel('Reps', { exact: true }).first()).toHaveValue('10')
  expect(errors).toEqual([])
})

test('shared appearance, contrast, responsive layout and logo rendering', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Crear rutina', exact: true })).toBeVisible()
  for (const theme of ['dark', 'light']) {
    await page.emulateMedia({ colorScheme: theme as 'dark' | 'light' })
    await expect(page.locator('html')).toHaveAttribute('data-theme-mode', 'system')
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
    await page.getByRole('button', { name: 'Elegir color de acento' }).click()
    await page.getByRole('menuitemradio', { name: 'Color Azul' }).click()
    await expect(page.locator('html')).toHaveAttribute('data-accent', 'blue')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(await page.locator('.brand-mark img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth === 192)).toBe(true)
    const findings = await new AxeBuilder({ page }).disableRules(['meta-viewport']).analyze()
    expect(findings.violations.filter((issue) => ['serious', 'critical'].includes(issue.impact ?? ''))).toEqual([])
    await page.screenshot({ path: info.outputPath(`home-${theme}.png`), fullPage: true })
  }
  await page.getByRole('button', { name: 'Elegir color de acento', exact: true }).click()
  await page.getByRole('button', { name: 'Elegir tema' }).click()
  await expect(page.getByRole('menuitemradio', { name: 'Color Azul' })).toHaveCount(0)
  await page.getByRole('menuitemradio', { name: 'Oscuro', exact: true }).click()
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Elegir tema' }).click()
  await page.getByRole('menuitemradio', { name: 'Dispositivo', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('meta[name="theme-color"]')).toHaveAttribute('content', '#0d0f12')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme-mode', 'system')
})
